"""Generate docs/canvas-url-directory.html - a crawlable list of Canvas URLs.

WHY THIS PAGE EXISTS, and why it is shaped the way it is
--------------------------------------------------------
Instructure already runs "Find My Canvas URL" and a school search on
instructure.com/canvas/login, and they own the head term outright. Checked
2026-08-27: searching for the query returns their tool, their login page and
their KB article, and an institution-specific search returns the university's
own page. We will not outrank either and should not try.

The one thing they do not offer is a **crawlable** list. Their search is
client-rendered, so no hostname is visible text to anything that does not run
JavaScript - which includes several assistant crawlers.

**That makes server-rendered rows the entire point of this build.** A page that
injected its rows with JavaScript would reproduce the competitor's only
weakness and have no reason to exist. Every institution below is in the HTML.
The filter box is added BY the script, so with JavaScript off a visitor gets
the full list rather than a search box that does nothing.

ONE PAGE, NOT 4,757. Google's spam policy defines scaled content abuse as many
pages generated to manipulate rankings rather than to help anyone. A single
filterable list of verified hostnames is a tool. Four thousand pages each
holding one name and one URL is what that policy is about. Do not generate
per-institution pages.

THE DATA is shared/institutions.py, generated by build_institution_list.py.
Every hostname there was proven at generation time to answer
/api/v1/users/self with Canvas's own unauthenticated payload, so it is a live
Canvas host rather than a parked domain or an SSO portal.

NOT GROUPED BY COUNTRY, deliberately: only 1,558 of 4,757 rows have a known
country, so country sections would put 3,199 institutions in an "unknown"
bucket and read as broken. Alphabetical, with the country shown as a chip
where it is known.

THE LIST IS NOT EXHAUSTIVE and the page must keep saying so, exactly as the
in-app picker does. A student whose school is missing must never conclude the
app does not support them.
"""
