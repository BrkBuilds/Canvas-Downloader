# The filter is INJECTED, so a visitor with JavaScript off gets the whole list
# instead of a search box that silently does nothing. It filters on a
# lower-cased name+host string built once, and it never touches the row set -
# rows are only hidden, so the page stays crawlable in every state.
PAGE_JS = """
  <script>
  (function () {
    var tbl = document.getElementById('dirtbl');
    if (!tbl) return;
    var rows = Array.prototype.slice.call(tbl.tBodies[0].rows);
    var keys = rows.map(function (r) { return (r.textContent || '').toLowerCase(); });
    var tools = document.getElementById('dirtools');
    var count = document.getElementById('dircount');
    var none = document.getElementById('dirnone');
    var inp = document.createElement('input');
    inp.type = 'search';
    inp.id = 'dirq';
    inp.placeholder = 'Search %s institutions...';
    inp.setAttribute('aria-label', 'Search institutions');
    tools.insertBefore(inp, tools.firstChild);
    var t = null;
    function apply() {
      var q = inp.value.trim().toLowerCase();
      var shown = 0;
      for (var i = 0; i < rows.length; i++) {
        var hit = !q || keys[i].indexOf(q) !== -1;
        rows[i].style.display = hit ? '' : 'none';
        if (hit) shown++;
      }
      // Explicit locale: bare toLocaleString() follows the BROWSER's, so on a
      // Danish machine the label flipped from the server-rendered "4,757" to
      // "4.757" the moment this script ran. The page is in English and the
      // static half of the label is already formatted that way.
      var fmt = function (x) { return x.toLocaleString('en-US'); };
      count.textContent = shown === rows.length
        ? fmt(rows.length) + ' institutions'
        : fmt(shown) + ' of ' + fmt(rows.length);
      none.style.display = shown ? 'none' : 'block';
    }
    inp.addEventListener('input', function () {
      if (t) clearTimeout(t);
      t = setTimeout(apply, 90);
    });
  })();
  </script>
"""


def rows_html() -> str:
    out = []
    for name, host, cc, _flags in DATA:
        cc = (cc or "").strip()
        chip = '<span class="dir-cc">%s</span>' % e(cc) if cc else ""
        # No data-k attribute: it duplicated the name and host that are
        # already in the cells, and measured 281 KB of the 1.24 MB page. The
        # filter builds its key from row.textContent instead, which is the
        # same string for free.
        out.append(
            '        <tr><td>%s %s</td>'
            '<td class="dir-host"><a href="https://%s" rel="nofollow noopener" '
            'target="_blank">%s</a></td></tr>'
            % (e(name), chip, e(host), e(host)))
    return "\n".join(out)


